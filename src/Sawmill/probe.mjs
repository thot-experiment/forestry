function findProbeFiles(root, out = []) {
    if (!fs.existsSync(root)) return out;
    for (const entry of fs.readdirSync(root, { withFileTypes: true })) {
        const full = path.join(root, entry.name);
        if (entry.isDirectory()) findProbeFiles(full, out);
        else if (entry.name === 'Probe.lua') out.push(full);
    }
    return out;
}

function makeStamp(meta) {
    const build = (meta && meta.build) || 'unknown';
    const version = (meta && meta.version) || 'v?';
    const ts = new Date((meta && meta.t ? meta.t * 1000 : Date.now()))
        .toISOString().replace(/[:.]/g, '').replace(/-/g, '').slice(0, 15);
    return `${version}-${build}-${ts}`;
}

function shapeReturns(types, sample) {
    if (!types || types.length === 0) return '(no returns)';
    return types.map((t, i) => {
        const s = sample && sample[i] !== undefined ? sample[i] : undefined;
        const sStr = s === undefined ? '' : ` = ${JSON.stringify(s)}`;
        return `${t}${sStr}`;
    }).join(', ');
}

function statusEmoji(status) {
    if (status === 'OK') return 'OK';
    if (status === 'MISSING') return 'MISSING';
    if (status === 'RAISED') return 'RAISED';
    return status;
}

function renderReport(run, eventLog) {
    const m = run.meta || {};
    const c = run.function_counts || {};
    const lines = [];
    lines.push(`# API Report`);
    lines.push('');
    lines.push(`Auto-generated by \`lumberjack --probe\`. Do not hand-edit. See METHODOLOGY.md §6.`);
    lines.push('');
    lines.push(`## Build`);
    lines.push('');
    lines.push(`- version: \`${m.version || '?'}\``);
    lines.push(`- build: \`${m.build || '?'}\``);
    lines.push(`- build date: \`${m.build_date || '?'}\``);
    lines.push(`- tocversion: \`${m.tocversion || '?'}\``);
    lines.push(`- project_id: \`${m.project_id || '?'}\``);
    lines.push(`- locale: \`${m.locale || '?'}\``);
    lines.push(`- probe addon version: \`${m.addon_version || '?'}\``);
    lines.push(`- probe run timestamp: \`${m.t || '?'}\` (\`${m.gt || '?'}\` GetTime)`);
    lines.push('');
    lines.push(`## Summary`);
    lines.push('');
    lines.push(`- Functions: ${c.OK || 0} OK, ${c.MISSING || 0} MISSING, ${c.RAISED || 0} RAISED`);
    lines.push(`- Events registered: ${(run.events_registered || []).length}`);
    lines.push(`- Events fired in this run: ${(eventLog || []).length}`);
    lines.push('');

    // Sort: failures first, then alphabetical.
    const fns = (run.functions || []).slice().sort((a, b) => {
        const order = { MISSING: 0, RAISED: 1, OK: 2 };
        const ad = order[a.status] ?? 3;
        const bd = order[b.status] ?? 3;
        if (ad !== bd) return ad - bd;
        return (a.name || '').localeCompare(b.name || '');
    });

    lines.push(`## Functions`);
    lines.push('');
    lines.push(`| status | name | returns | site | notes |`);
    lines.push(`|---|---|---|---|---|`);
    for (const r of fns) {
        let ret;
        if (r.status === 'OK' && r.skipped) {
            ret = '(existence-only check)';
        } else if (r.status === 'OK') {
            ret = shapeReturns(r.return_types, r.sample);
        } else if (r.status === 'RAISED') {
            ret = `error: ${r.error || ''}`;
        } else {
            ret = `actual type: ${r.actual_type || 'nil'}`;
        }
        lines.push(`| ${statusEmoji(r.status)} | \`${r.name}\` | ${escapeMd(ret)} | ${escapeMd(r.site || '')} | ${escapeMd(r.notes || '')} |`);
    }
    lines.push('');

    lines.push(`## Events registered`);
    lines.push('');
    lines.push(`| event | registered | site | notes |`);
    lines.push(`|---|---|---|---|`);
    for (const e of (run.events_registered || [])) {
        lines.push(`| \`${e.event}\` | ${e.registered_ok ? 'yes' : 'no'} | ${escapeMd(e.site || '')} | ${escapeMd(e.notes || '')} |`);
    }
    lines.push('');

    if (eventLog && eventLog.length > 0) {
        lines.push(`## Events observed (this session)`);
        lines.push('');
        lines.push(`| event | argc | argv types | sample |`);
        lines.push(`|---|---|---|---|`);
        for (const e of eventLog) {
            const types = (e.argv_types || []).join(', ');
            const sample = JSON.stringify(e.argv_sample || {});
            lines.push(`| \`${e.event}\` | ${e.argc || 0} | ${escapeMd(types)} | ${escapeMd(sample)} |`);
        }
        lines.push('');
    } else {
        lines.push(`## Events observed (this session)`);
        lines.push('');
        lines.push(`_None observed yet. Trigger the events in-game and re-run probe._`);
        lines.push('');
    }

    return lines.join('\n');
}

function escapeMd(s) {
    if (s === null || s === undefined) return '';
    return String(s).replace(/\|/g, '\\|').replace(/\n/g, ' ');
}
